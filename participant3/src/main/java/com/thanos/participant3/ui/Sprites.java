    private Sprites() { }

    /** The sprite for an enemy by name, or null when there is none. */
    public static PixelSprite forEnemy(String name) {
        if (name == null) return null;
        return switch (name) {
            case "Outrider" -> OUTRIDER;
            case "Chitauri" -> CHITAURI;
            case "Sakaaran" -> SAKAARAN;
            case "In-Betweener" -> IN_BETWEENER;
            case "Champion" -> CHAMPION;
            case "Gardener" -> GARDENER;
            case "Runner" -> RUNNER;
            case "Collector" -> COLLECTOR;
            case "Grandmaster" -> GRANDMASTER;
            default -> null;
        };
    }

    /** The stone a gauntlet key stands for, or null. */
    public static InfinityStone stoneOf(char key) {
        int i = STONE_KEYS.indexOf(key);
        return i < 0 ? null : InfinityStone.values()[i];
    }

    /** Top left pixel of the stone's 2x2 socket in THANOS, counted from the top row. */
    public static int[] socket(InfinityStone stone) {
        char key = STONE_KEYS.charAt(stone.ordinal());
        for (int y = 0; y < THANOS.height(); y++) {
            for (int x = 0; x < THANOS.width(); x++) {
                if (THANOS.key(x, y) == key) return new int[] {x, y};
            }
        }
        throw new IllegalStateException("No socket for " + stone);
    }
